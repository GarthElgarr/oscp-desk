const CARDS = new Map(Object.entries(TITLES));

export type DeskCard = { id: string; section: string; title: string };

/** The service card for an nmap port. The service name wins over the port number. */
export function deskCard(port: string, service: string, tunnel = ""): DeskCard | null {
  const name = service.toLowerCase().trim();
  const base = name.replace(/^ssl\//, "");
  const ssl = tunnel === "ssl" || name.startsWith("ssl/") || base === "https";
  let id = "";
  if ((base === "http" || base === "http-alt" || base === "https") && (ssl || port === "443" || port === "8443")) id = "svc-https";
  else if (BY_SERVICE[base]) id = BY_SERVICE[base];
  else if (BY_SERVICE[name]) id = BY_SERVICE[name];
  else id = BY_PORT[port] ?? "";
  const title = CARDS.get(id);
  if (!title) return null;
  return { id, section: "Services", title };
}

export function deskCardHref(card: DeskCard): string {
  return `/?section=${encodeURIComponent(card.section)}&card=${encodeURIComponent(card.id)}`;
}
